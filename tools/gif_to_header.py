#!/usr/bin/env python3
"""
Convert an animated GIF into heart_anim.h for the ESPHome word clock.

The original firmware downloaded heart_art_small.gif at boot and decoded it with
AnimatedGIF. In ESPHome we embed the frames at build time instead: no HTTP client,
no malloc, no 32 KB limit, and it works with the clock offline.

Usage:
    pip install pillow
    python3 tools/gif_to_header.py tools/heart.gif -o components/wordclock/heart_anim.h --fixed-delay 100
"""
import argparse
import sys

from PIL import Image, ImageSequence

W, H = 12, 11  # must match the LED grid in wordclock.h


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("gif")
    ap.add_argument("-o", "--output", default="heart_anim.h")
    ap.add_argument("--min-delay", type=int, default=30, help="clamp frame delay (ms), default 30")
    ap.add_argument("--smooth", action="store_true",
                    help="use bilinear resize if the GIF is not already 12x11 (default: nearest)")
    ap.add_argument("--max-frames", type=int, default=120)
    ap.add_argument("--fixed-delay", type=int, default=None, metavar="MS",
                    help="ignore the GIF's own timing and show every frame for MS ms "
                         "(the Pi controller plays heart.gif at a fixed 100 ms/frame)")
    args = ap.parse_args()

    im = Image.open(args.gif)
    resample = Image.BILINEAR if args.smooth else Image.NEAREST

    frames, delays = [], []
    for fr in ImageSequence.Iterator(im):
        delay = fr.info.get("duration", 100) or 100
        rgba = fr.copy().convert("RGBA")
        # Transparent pixels -> black (LEDs off), same effect as the original disposal handling
        canvas = Image.new("RGBA", rgba.size, (0, 0, 0, 255))
        canvas.alpha_composite(rgba)
        rgb = canvas.convert("RGB")
        if rgb.size != (W, H):
            rgb = rgb.resize((W, H), resample)
        frames.append(rgb)
        delays.append(args.fixed_delay if args.fixed_delay else max(delay, args.min_delay))

    if not frames:
        sys.exit("No frames found in GIF")
    if len(frames) > args.max_frames:
        print(f"warning: {len(frames)} frames, truncating to {args.max_frames}", file=sys.stderr)
        frames, delays = frames[: args.max_frames], delays[: args.max_frames]

    if im.size != (W, H):
        print(f"note: GIF is {im.size[0]}x{im.size[1]}, resized to {W}x{H}", file=sys.stderr)

    out = []
    out.append("#pragma once")
    out.append(f"// Generated by tools/gif_to_header.py from {args.gif.split('/')[-1]} - do not edit by hand")
    out.append("#include <cstdint>")
    out.append("")
    out.append("namespace wc_heart {")
    out.append(f"constexpr int FRAME_COUNT = {len(frames)};")
    out.append(f"constexpr uint32_t TOTAL_MS = {sum(delays)};")
    out.append(f"constexpr uint16_t DELAYS_MS[FRAME_COUNT] = {{{', '.join(str(d) for d in delays)}}};")
    out.append("// FRAMES[frame][y][x][rgb], y=0 is the top row, x=0 the left column")
    out.append("constexpr uint8_t FRAMES[FRAME_COUNT][11][12][3] = {")
    for fr in frames:
        out.append("  {")
        for y in range(H):
            row = ", ".join("{%d,%d,%d}" % fr.getpixel((x, y)) for x in range(W))
            out.append("    {" + row + "},")
        out.append("  },")
    out.append("};")
    out.append("}  // namespace wc_heart")
    out.append("")

    with open(args.output, "w") as f:
        f.write("\n".join(out))
    print(f"wrote {args.output}: {len(frames)} frames, {sum(delays)} ms loop")


if __name__ == "__main__":
    main()
